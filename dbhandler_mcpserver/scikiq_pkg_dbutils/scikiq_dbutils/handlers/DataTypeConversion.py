def convertDataType(col_detail_list, dstn_db_type):
    db_type = dstn_db_type.upper()
    if db_type == "VERTICA" :
        for count, column_dict in enumerate(col_detail_list):
            try :
                column_dtype = column_dict['DATA_TYPE']
                if '[(' in column_dtype:
                    column_dtype = column_dtype.split("[(")[0] 
                elif '(' in column_dtype:
                    column_dtype = column_dtype.split("(")[0]
                column_dtype = column_dtype.upper()
                if column_dtype:
                    col_detail_list[count]['DATA_TYPE_ORG'] = col_detail_list[count]['DATA_TYPE']
                    col_detail_list[count]['DATA_TYPE'] = dictDstVerticaShort[column_dtype]
            except Exception as e :
                print(" VERTICA convertDataType , Unsupported Data Type :" + str(e))
    ## post gres returns everything in lower case whereas other database
    ## it is in upper case
    elif db_type in ("POSTGRES","REDSHIFT") :
        for count, column_dict in enumerate(col_detail_list):
            try :
                column_dtype = column_dict['DATA_TYPE'].strip().upper()
                col_detail_list[count]['DATA_TYPE_ORG'] = col_detail_list[count]['DATA_TYPE']
                col_detail_list[count]['DATA_TYPE'] = dictMain[db_type][column_dtype]
            except Exception as e :
                print("POSTGRES convertDataType , Unsupported Data Type :" + str(e))            
    else :
        for count, column_dict in enumerate(col_detail_list):
            try :
                column_dtype = column_dict['DATA_TYPE'].strip().upper()
                ## incase of Oracle data type of timestamp comes with size like TIMESTAMP(6)
                if "(" in column_dtype :
                    column_dtype =  column_dtype.split("(")[0] 

                col_detail_list[count]['DATA_TYPE_ORG'] = col_detail_list[count]['DATA_TYPE']
                col_detail_list[count]['DATA_TYPE'] = dictMain[db_type][column_dtype]
                if db_type == 'ORACLE':
                    if col_detail_list[count]['NUMERIC_PRECISION'] is None\
                            and col_detail_list[count]['DATA_TYPE_ORG'] == 'NUMBER':
                        col_detail_list[count]['DATA_TYPE'] = 'INT'
            except Exception as e :
                print(db_type + " convertDataType , Unsupported Data Type :" + str(e))            
    
    return col_detail_list